function Section({
  title,
  children,
}: {
  title: string;
  children: React.ReactNode;
}) {
  return (
    <section>
      <h2 className="text-base font-semibold text-steel-900">{title}</h2>
      <div className="mt-3 space-y-3">{children}</div>
    </section>
  );
}

function List({ items }: { items: React.ReactNode[] }) {
  return (
    <ul className="list-disc space-y-1.5 pl-5 marker:text-steel-300">
      {items.map((item, i) => (
        <li key={i}>{item}</li>
      ))}
    </ul>
  );
}

/** Карточка цели обработки: цель, основание, данные, субъекты, действия, способ, срок */
function Purpose({ title, rows }: { title: string; rows: [string, string][] }) {
  return (
    <div className="rounded-xl border border-steel-200 bg-steel-50/60">
      <h3 className="border-b border-steel-200 px-4 py-3 text-sm font-semibold text-steel-900">
        {title}
      </h3>
      <dl className="divide-y divide-steel-200/70">
        {rows.map(([label, value]) => (
          <div
            key={label}
            className="grid gap-1 px-4 py-2.5 sm:grid-cols-[200px_minmax(0,1fr)] sm:gap-4"
          >
            <dt className="text-xs font-semibold text-steel-500">{label}</dt>
            <dd>{value}</dd>
          </div>
        ))}
      </dl>
    </div>
  );
}

/** Таблица: на узком экране прокручивается вбок, страница при этом не ломается */
function Table({ headers, rows }: { headers: string[]; rows: string[][] }) {
  return (
    <div className="overflow-x-auto rounded-xl border border-steel-200">
      <table className="w-full min-w-[480px] text-left">
        <thead className="bg-steel-50 text-xs font-semibold text-steel-500">
          <tr>
            {headers.map((h) => (
              <th key={h} className="px-4 py-2.5 align-top">
                {h}
              </th>
            ))}
          </tr>
        </thead>
        <tbody className="divide-y divide-steel-200/70">
          {rows.map((row, i) => (
            <tr key={i}>
              {row.map((cell, j) => (
                <td key={j} className="px-4 py-2.5 align-top">
                  {cell}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

