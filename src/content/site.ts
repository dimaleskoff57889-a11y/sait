export type Service = {
  /** Короткое название работы */
  title: string;
  /** 1-2 предложения, что именно входит */
  text: string;
  /** Иконка: из набора в src/components/icons.ts */
  icon: "wrench" | "hammer" | "refresh" | "shield" | "siren" | "gauge";
  /** Основной хлеб (1.2) — такие карточки показываем первыми и крупнее */
  primary?: boolean;
};

export type WorkObject = {
  /** Название объекта. Если называть нельзя (2.2) — обобщённо */
  name: string;
  /** Вид работ — короткая оранжевая подпись над названием */
  work: string;
  /** Описание работ — абзац под названием */
  text: string;
  /** Год или период, если помнит */
  year?: string;
  /**
   * Фото этого объекта — файл в public/photos. В «Объектах» одна стопка:
   * одно фото = один объект, при листании справа меняются название и
   * описание. Пусто — заглушка на месте фото.
   */
  photo?: string;
  /**
   * Логотипы компании-объекта — файлы в public/logos/objects. Показываются в
   * стопке, пока нет фото (photo важнее). Пусто и нет фото — карточка с названием.
   */
  logos?: string[];
};

export type Partner = {
  name: string;
  /** Логотип — файл в public/logos. Пусто — плашка-заглушка с иконкой */
  logo?: string;
  /** Логотип светлый (белый на прозрачном) — показывать на тёмной плашке */
  logoOnDark?: boolean;
  /**
   * Показывать только эмблему — левый квадрат широкого логотипа (без надписи).
   * Нужно, когда надпись на логотипе расходится с подписью в строке.
   */
  logoEmblemOnly?: boolean;
};

export type Step = {
  title: string;
  text: string;
};

export type Document = {
  title: string;
  issuer?: string;
  /** Файл-скан в public/docs — если решим показывать */
  scan?: string;
};

